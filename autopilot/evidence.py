"""Проверка, предмет которой правил проверяемый, доказательством не считается.

Единственное место во всей приёмке, где право закрыть задачу фактически
отдано тому, кого проверяют. Схема простая и до этого модуля работала:

* критерий задачи — `cd backend && .venv/Scripts/python -m pytest tests/test_cart.py`;
* каталог `tests/` пишет и держит **сам агент**, в том же рабочем каталоге;
* `_check_shell` считает пройденным всё, у чего код возврата ноль
  (`verifier.py`), и такая проверка идёт в `deterministic`, то есть
  в ДОКАЗАТЕЛЬСТВА, по которым задача закрывается автоматически.

Ослабить собственный тест — законный путь к `exit=0`, а значит к
`Verdict.confirmed`. Ни одного рубежа против этого не стояло: `suspicious()`
ловит пустышки вроде `http 200` на корне, но `pytest` по настоящему файлу
для неё — полноценная проверка, каким бы этот файл ни стал.

**Правило ровно одно, и оно узкое:** критерий ЯВНО НАЗЫВАЕТ файл, а агент
этот файл ИЗМЕНИЛ ИЛИ УДАЛИЛ. Создание не считается: написать тест — это
работа, ради которой задачу и заводили; переписать существующий — это
потеря доказательства.

Второе правило («голый раннер ⇒ любой файл, похожий на тест») рассматривалось
и отброшено: на живом плане голых раннеров нет ни одного, а поверхность
ложных срабатываний у него самая широкая.

**Изменения берутся НАКОПИТЕЛЬНО по всем сборкам задачи.** Цикл идёт
build → verify → fail → build → verify. Если тест ослаблен на первой сборке,
а вторая его не трогала, то приёмка второй попытки по «последней сборке»
пятна не увидела бы — и механизм закрывал бы дыру только на первом круге.

**Чего правило не умеет:** содержимое правки мы не читаем. Тест, поправленный
по делу (изменился интерфейс), и тест, ослабленный ради зелёного прогона,
для этого модуля неотличимы. Задача из-за пятна не проваливается — она
перестаёт закрываться САМА и уходит владельцу на `/confirm`. Это осознанный
размен: ложное пятно стоит одного решения человека, пропущенное — закрытой
задачи, которую никто не проверял.
"""
from __future__ import annotations

import logging
import re

from .config import cfg

log = logging.getLogger("evidence")

# Разделитель БЕРЁТСЯ У `paths`, а не копируется. Общий у двух модулей
# только он: `paths.of` возвращает КАТАЛОГИ по двум сегментам, а здесь нужны
# имена файлов целиком. Но резать командную строку критерия они обязаны
# одинаково — две копии одной регулярки разойдутся на первой же правке,
# и разойдутся молча.
from .paths import _SPLIT

# Файл, а не каталог и не флаг: с расширением и без ведущего дефиса.
_FILE = re.compile(r"^[^-][^\s]*\.[A-Za-z0-9]{1,8}$")


def files_of(check: dict) -> set[str]:
    """Файлы, ЯВНО названные в критерии.

    `pytest tests/test_cart.py::test_total` → `tests/test_cart.py`.
    `pytest tests/` → ничего: каталог файлом не является, и подставлять
    вместо него «всё, что похоже на тест» — это уже догадка.
    """
    out: set[str] = set()
    if not isinstance(check, dict):
        return out
    for key in ("path", "cmd"):
        for token in _SPLIT.split(str(check.get(key) or "")):
            token = token.strip().strip(",").lstrip("./")
            if not token:
                continue
            head = token.split("::")[0].replace("\\", "/")
            if _FILE.match(head):
                out.add(head)
    return out


def _tail_match(named: str, changed: str) -> bool:
    """Совпадают ли путь из критерия и путь из слепка.

    Критерий пишется относительно СВОЕГО каталога (`cd backend && pytest
    tests/test_cart.py`), а слепок — относительно корня рабочего каталога
    (`backend/tests/test_cart.py`). Поэтому сравниваем по хвосту, а не
    посимвольно, и требуем совпадения по границе сегмента: `test_cart.py`
    не должен совпадать с `my_test_cart.py`.
    """
    named = named.strip("/").lower()
    changed = changed.strip("/").lower()
    if named == changed:
        return True
    return changed.endswith("/" + named)


def tainted(check: dict, touched) -> set[str]:
    """Какие названные критерием файлы агент переписал или удалил."""
    if not touched:
        return set()
    named = files_of(check)
    if not named:
        return set()
    return {n for n in named if any(_tail_match(n, c) for c in touched)}


def review(acceptance, touched) -> dict[int, set[str]]:
    """Индексы критериев, потерявших доказательность, и чем именно.

    `touched` — накопительно по всем сборкам задачи: только `modified`
    и `deleted`, без `created`.
    """
    if not cfg.evidence_taint or not touched:
        return {}
    out: dict[int, set[str]] = {}
    for i, check in enumerate(acceptance or []):
        hit = tainted(check, touched)
        if hit:
            out[i] = hit
    return out


def note(files) -> str:
    """Строка для владельца и для журнала."""
    names = ", ".join(sorted(files))
    return (f"проверку правил тот, кого она проверяет: агент переписал {names}. "
            f"Доказательством она больше не считается")
