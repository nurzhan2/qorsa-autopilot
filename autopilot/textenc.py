"""Байты дочернего процесса — в текст, а не в кракозябры.

На этой машине консольная кодовая страница — cp866 (русская DOS): именно
в ней `cmd.exe`, `flutter.bat` и системные сообщения Windows («Система не
может найти путь») печатают текст, а не в UTF-8. Слепой
`bytes.decode(errors="replace")` без указания кодировки читает как UTF-8
и на не-UTF-8 байтах не восстанавливает текст, а стирает его в `�`.

Живой случай: дефект задачи 536 в базе — `���⥬�...`
вместо русского текста ошибки flutter. Восстановить его после записи уже
нельзя — байты потеряны на этапе decode(). Поэтому декодировать правильно
нужно один раз, на входе, до того как текст попадёт в базу.
"""
from __future__ import annotations

CANDIDATES = ("utf-8", "cp866", "cp1251")


def decode_console(data: bytes | None) -> str:
    """Пробует кодировки по порядку и берёт ту, что дала меньше всего `\\ufffd`.

    UTF-8 идёт первым и побеждает всегда, когда текст действительно в UTF-8
    (так пишут большинство *nix-инструментов и сам Python): валидный UTF-8
    декодируется без единого `\\ufffd`, и до однобайтовых кодировок дело
    не доходит. Cp866/cp1251 — однобайтовые, они «декодируют» вообще любые
    байты без ошибок, поэтому годятся только как проигрышный вариант UTF-8:
    если в UTF-8 нашлась хоть одна замена, значит это не UTF-8, и cp866
    (родная кодировка русской консоли Windows) читает такой текст правильно.
    """
    if not data:
        return ""
    best_text, best_bad = None, None
    for enc in CANDIDATES:
        text = data.decode(enc, errors="replace")
        bad = text.count("�")
        if bad == 0:
            return text
        if best_bad is None or bad < best_bad:
            best_text, best_bad = text, bad
    return best_text
